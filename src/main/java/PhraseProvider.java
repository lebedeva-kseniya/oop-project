    public String getRandomGreeting() {
        return greetingPhrases.get(random.nextInt(greetingPhrases.size()));
    }

    public String getAttemptPhrase(int attemptNumber, StringBuilder currentWord, StringBuilder nearbyLetters) {
        String phrase = attemptPhrases.get(random.nextInt(attemptPhrases.size()));
        return String.format(phrase, attemptNumber, currentWord.toString(), nearbyLetters.toString());
    }

    public String getRandomWinPhrase(String word, int attemptCount) {
        String phrase = gameWinPhrases.get(random.nextInt(gameWinPhrases.size()));
        return String.format(phrase, word, attemptCount);
    }

    public String getRandomEnding() {
        return endGamePhrases.get(random.nextInt(endGamePhrases.size()));
    }

